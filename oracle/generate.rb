# Writes the corpus-driven test programs from oracle/data/corpus.json.
# oracle/record.rb collected that corpus: every String Loofah 2.25.2's own
# test suite passed to Loofah's entry points (fragment and document
# parsing, the scrub_* shortcuts, HTML5::Scrub.scrub_css and allowed_uri?).
# To collect it again, run the suite at the v2.25.2 tag:
#
#   MT_NO_PLUGINS=1 ruby -Itest -r<path>/oracle/record.rb \
#     -e 'Dir["test/**/test_*.rb"].each { |f| require "./#{f}" }'
#
# The inputs are embedded as literals, so the compiled tests read no files.
# The EXPECTED output is not written here: `sh oracle/run.sh --regen` takes
# it from the real gem.
#
# Usage: ruby oracle/generate.rb   (from the repo root)
require "json"

CORPUS = JSON.parse(File.read(File.join(__dir__, "data", "corpus.json")))

def pick(*keys)
  keys.flat_map { |k| CORPUS.fetch(k, []) }.uniq
end

def literal_array(strings)
  "[\n" + strings.map { |s| "  #{s.inspect},\n" }.join + "]"
end

# Beyond the suite's inputs: style values whose numbers are past 64 bits
# (spinel-crass computes those as Floats; the scrubbed text must not change).
BIG_NUMBERS = [
  "width: 12345678901234567890px; color: red",
  "margin: 1234567890.123456789e-10px 99999999999999999999.5em",
  "width: 1e99999999999999999999px; top: -1e-5000000px; z-index: 9223372036854775808",
  "padding: 0.000000000000000000000001px 9223372036854775807px",
]

FRAGMENTS = pick("html4_fragment", "html5_fragment", "scrub_html4_fragment",
                 "scrub_html5_fragment", "fragment", "scrub_fragment")
DOCUMENTS = pick("html4_document", "html5_document", "scrub_html4_document",
                 "scrub_html5_document", "document", "scrub_document")

# The fragments the link and text scrubbers have something to do with.
SHAPED = FRAGMENTS.select { |s| s =~ /<a\b|<p\b|<br| | |<div|<li/i }

# `err` keeps a raise from ending the run: the class and message are the
# answer, on both sides.
GUARD = <<~RUBY
  def guarded
    yield
  rescue StandardError => e
    "!\#{e.class}: \#{e.message}"
  end
RUBY

{
  "sanitize_html4" => ["html4", %w[escape prune strip whitewash], FRAGMENTS],
  "sanitize_html5" => ["html5", %w[escape prune strip whitewash], FRAGMENTS],
  "links_html4" => ["html4", %w[nofollow noopener noreferrer targetblank unprintable
                                newline_block_elements double_breakpoint], SHAPED],
  "links_html5" => ["html5", %w[nofollow noopener noreferrer targetblank unprintable
                                newline_block_elements double_breakpoint], SHAPED],
}.each do |name, (html, scrubbers, inputs)|
  File.write("test/#{name}_test.rb", <<~RUBY)
    # GENERATED by oracle/generate.rb: every fragment Loofah's own suite
    # parses#{inputs.equal?(SHAPED) ? " (the ones holding links, paragraphs and breaks)" : ""},
    # as a Loofah::#{html.upcase}::DocumentFragment, scrubbed by each of
    # #{scrubbers.map { |s| ":#{s}" }.join(", ")}.
    require "loofah"

    #{GUARD.strip}

    INPUTS = #{literal_array(inputs)}

    SCRUBBERS = #{scrubbers.map(&:to_sym).inspect}

    INPUTS.each_with_index do |input, i|
      SCRUBBERS.each do |scrubber|
        out = guarded { Loofah.#{html}_fragment(input).scrub!(scrubber).to_html }
        puts "\#{i} \#{scrubber}: \#{out}"
      end
    end
  RUBY
end

File.write("test/documents_test.rb", <<~RUBY)
  # GENERATED by oracle/generate.rb: every document Loofah's own suite
  # parses, as HTML4 and HTML5 Loofah documents: scrubbed :strip and
  # :prune, then its text, to_text and serialization, and the same of the
  # document's body as a fragment.
  require "loofah"

  #{GUARD.strip}

  INPUTS = #{literal_array(DOCUMENTS)}

  INPUTS.each_with_index do |input, i|
    [:strip, :prune].each do |scrubber|
      puts "\#{i} html4 \#{scrubber}: " + guarded { Loofah.html4_document(input).scrub!(scrubber).to_html }
      puts "\#{i} html5 \#{scrubber}: " + guarded { Loofah.html5_document(input).scrub!(scrubber).to_html }
    end
    puts "\#{i} html4 text: " + guarded { Loofah.html4_document(input).text }
    puts "\#{i} html5 text: " + guarded { Loofah.html5_document(input).text }
    puts "\#{i} html4 to_text: " + guarded { Loofah.html4_document(input).to_text }
    puts "\#{i} html5 to_text: " + guarded { Loofah.html5_document(input).to_text }
    puts "\#{i} html5 raw text: " + guarded { Loofah.html5_document(input).text(encode_special_chars: false) }
  end
RUBY

File.write("test/text_test.rb", <<~RUBY)
  # GENERATED by oracle/generate.rb: every fragment Loofah's own suite
  # parses, as text — escaped, raw, and to_text's block-level newlines —
  # from both parsers.
  require "loofah"

  #{GUARD.strip}

  INPUTS = #{literal_array(FRAGMENTS)}

  INPUTS.each_with_index do |input, i|
    puts "\#{i} html4 text: " + guarded { Loofah.html4_fragment(input).text }
    puts "\#{i} html5 text: " + guarded { Loofah.html5_fragment(input).text }
    puts "\#{i} html5 raw: " + guarded { Loofah.html5_fragment(input).text(encode_special_chars: false) }
    puts "\#{i} html4 to_text: " + guarded { Loofah.html4_fragment(input).to_text }
    puts "\#{i} html5 to_text: " + guarded { Loofah.html5_fragment(input).to_text }
  end
RUBY

File.write("test/scrub_test.rb", <<~RUBY)
  # GENERATED by oracle/generate.rb: Loofah::HTML5::Scrub's two string
  # functions on every input Loofah's own suite hands them — scrub_css on
  # style values, allowed_uri? on URIs.
  require "loofah"

  #{GUARD.strip}

  STYLES = #{literal_array(pick("scrub_css") + BIG_NUMBERS)}

  URIS = #{literal_array(pick("allowed_uri?"))}

  STYLES.each_with_index do |style, i|
    puts "\#{i} css: " + guarded { Loofah::HTML5::Scrub.scrub_css(style) }
  end
  URIS.each_with_index do |uri, i|
    puts "\#{i} uri: " + guarded { Loofah::HTML5::Scrub.allowed_uri?(uri).to_s }
  end
RUBY

puts "wrote #{Dir["test/*_test.rb"].sort.join(" ")}"
